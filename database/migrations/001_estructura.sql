-- BD-01. Fuente: modelo.json (21 entidades), RN y D-09/D-13.
-- Los CHECK de estados concretan técnicamente los nombres propuestos en 01/08.
-- No aprueban transiciones, cupos, periodos, rúbricas ni condiciones de inicio.
-- D-01..D-08 y D-10..D-12 permanecen pendientes: sin valores por defecto de cupo.
CREATE SCHEMA banco;
REVOKE ALL ON SCHEMA banco FROM PUBLIC;

CREATE TABLE banco.usuario (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL CHECK (btrim(nombre) <> ''),
  correo_normalizado text NOT NULL UNIQUE,
  hash_contrasena text NOT NULL CHECK (btrim(hash_contrasena) <> ''),
  rol_principal text NOT NULL CHECK (rol_principal IN ('empresa','alumno','profesor','administrador')),
  estado_cuenta text NOT NULL DEFAULT 'activa' CHECK (estado_cuenta IN ('activa','inactiva')),
  fecha_alta timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_correo_normalizado CHECK (
    correo_normalizado = lower(btrim(correo_normalizado)) AND correo_normalizado <> '')
);

CREATE TABLE banco.empresa (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  razon_social text NOT NULL CHECK (btrim(razon_social) <> ''),
  sector text,
  identificacion text,
  contacto_nombre text,
  contacto_correo text,
  contacto_telefono text
);

CREATE TABLE banco.representacion_empresa (
  usuario_id bigint PRIMARY KEY REFERENCES banco.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  empresa_id bigint NOT NULL REFERENCES banco.empresa(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  vigente boolean NOT NULL DEFAULT true,
  fecha_vinculacion timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_fin timestamptz,
  CONSTRAINT ck_representacion_fechas CHECK (
    (vigente AND fecha_fin IS NULL) OR
    (NOT vigente AND fecha_fin IS NOT NULL AND fecha_fin >= fecha_vinculacion))
);
CREATE UNIQUE INDEX uq_representante_vigente ON banco.representacion_empresa(empresa_id) WHERE vigente;
CREATE INDEX ix_representacion_empresa ON banco.representacion_empresa(empresa_id);

CREATE TABLE banco.alumno (
  usuario_id bigint PRIMARY KEY REFERENCES banco.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  matricula text NOT NULL UNIQUE CHECK (btrim(matricula) <> ''),
  carrera text,
  semestre smallint CHECK (semestre > 0),
  datos_academicos text,
  contacto_correo text,
  contacto_telefono text
);
CREATE TABLE banco.profesor (
  usuario_id bigint PRIMARY KEY REFERENCES banco.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  numero_empleado text NOT NULL UNIQUE CHECK (btrim(numero_empleado) <> ''),
  especialidad text,
  experiencia text,
  contacto_correo text,
  contacto_telefono text
);

CREATE TABLE banco.proyecto (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id bigint NOT NULL REFERENCES banco.empresa(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  autor_usuario_id bigint NOT NULL REFERENCES banco.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  titulo text NOT NULL CHECK (btrim(titulo) <> ''),
  descripcion text,
  problematica text,
  objetivos text,
  justificacion text,
  alcance text,
  requisitos_academicos text,
  duracion_estimada text,
  modalidad text,
  fecha_inicio_estimada date,
  fecha_fin_estimada date,
  recursos text,
  estado text NOT NULL DEFAULT 'borrador' CHECK (estado IN
    ('borrador','en_revision','en_correccion','publicado','rechazado','en_curso','finalizado','cancelado')),
  CONSTRAINT ck_proyecto_fechas CHECK (
    fecha_inicio_estimada IS NULL OR fecha_fin_estimada IS NULL OR fecha_fin_estimada >= fecha_inicio_estimada)
);
CREATE INDEX ix_proyecto_empresa ON banco.proyecto(empresa_id);
CREATE INDEX ix_proyecto_autor ON banco.proyecto(autor_usuario_id);
CREATE INDEX ix_proyecto_estado ON banco.proyecto(estado);

CREATE TABLE banco.revision_proyecto (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proyecto_id bigint NOT NULL REFERENCES banco.proyecto(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  autor_usuario_id bigint NOT NULL REFERENCES banco.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  numero integer NOT NULL CHECK (numero > 0),
  fecha_envio timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  estado_revision text NOT NULL DEFAULT 'en_revision' CHECK (estado_revision IN
    ('en_revision','aprobada','en_correccion','rechazada')),
  instantanea_contenido jsonb NOT NULL CHECK (jsonb_typeof(instantanea_contenido) = 'object'),
  CONSTRAINT uq_revision_numero UNIQUE (proyecto_id,numero)
);
CREATE INDEX ix_revision_autor ON banco.revision_proyecto(autor_usuario_id);

CREATE TABLE banco.habilidad (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL CHECK (btrim(nombre) <> ''),
  tipo text NOT NULL CHECK (tipo IN ('dura','blanda')),
  descripcion text
);
CREATE TABLE banco.alumno_habilidad (
  alumno_id bigint NOT NULL REFERENCES banco.alumno(usuario_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  habilidad_id bigint NOT NULL REFERENCES banco.habilidad(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  nivel_dominio text,
  descripcion text,
  evidencia text,
  PRIMARY KEY (alumno_id,habilidad_id)
);
CREATE INDEX ix_alumno_habilidad_catalogo ON banco.alumno_habilidad(habilidad_id);
CREATE TABLE banco.proyecto_habilidad (
  proyecto_id bigint NOT NULL REFERENCES banco.proyecto(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  habilidad_id bigint NOT NULL REFERENCES banco.habilidad(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  nivel_minimo text,
  obligatoria boolean NOT NULL DEFAULT false,
  PRIMARY KEY (proyecto_id,habilidad_id)
);
CREATE INDEX ix_proyecto_habilidad_catalogo ON banco.proyecto_habilidad(habilidad_id);

CREATE TABLE banco.candidatura (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alumno_id bigint NOT NULL REFERENCES banco.alumno(usuario_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  proyecto_id bigint NOT NULL REFERENCES banco.proyecto(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  fecha_solicitud timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  estado text NOT NULL DEFAULT 'pendiente_evaluacion' CHECK (estado IN
    ('pendiente_evaluacion','evaluada','preseleccionada','aprobada','rechazada','cancelada')),
  observaciones text,
  CONSTRAINT uq_candidatura_origen UNIQUE (id,alumno_id,proyecto_id)
);
CREATE INDEX ix_candidatura_alumno ON banco.candidatura(alumno_id);
CREATE INDEX ix_candidatura_proyecto ON banco.candidatura(proyecto_id);
-- Sin índice de candidatura "activa": el predicado depende de D-06.
CREATE TABLE banco.solicitud_direccion (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profesor_id bigint NOT NULL REFERENCES banco.profesor(usuario_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  proyecto_id bigint NOT NULL REFERENCES banco.proyecto(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  fecha_solicitud timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  experiencia_aplicable text,
  justificacion text,
  estado text NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','aprobada','rechazada','cancelada')),
  CONSTRAINT uq_solicitud_direccion_origen UNIQUE (id,profesor_id,proyecto_id)
);
CREATE INDEX ix_solicitud_direccion_profesor ON banco.solicitud_direccion(profesor_id);
CREATE INDEX ix_solicitud_direccion_proyecto ON banco.solicitud_direccion(proyecto_id);

CREATE TABLE banco.decision_administrativa (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  administrador_usuario_id bigint NOT NULL REFERENCES banco.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  revision_proyecto_id bigint REFERENCES banco.revision_proyecto(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  candidatura_id bigint REFERENCES banco.candidatura(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  solicitud_direccion_id bigint REFERENCES banco.solicitud_direccion(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  fecha timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resultado text NOT NULL CHECK (resultado IN ('aprobada','rechazada','en_correccion')),
  justificacion text NOT NULL CHECK (btrim(justificacion) <> ''),
  CONSTRAINT ck_decision_objeto_unico CHECK
    (num_nonnulls(revision_proyecto_id,candidatura_id,solicitud_direccion_id) = 1),
  CONSTRAINT ck_correccion_solo_revision CHECK (resultado <> 'en_correccion' OR revision_proyecto_id IS NOT NULL),
  CONSTRAINT uq_decision_candidatura UNIQUE (id,candidatura_id,resultado),
  CONSTRAINT uq_decision_direccion UNIQUE (id,solicitud_direccion_id,resultado)
);
CREATE INDEX ix_decision_administrador ON banco.decision_administrativa(administrador_usuario_id);
CREATE INDEX ix_decision_revision ON banco.decision_administrativa(revision_proyecto_id);
CREATE INDEX ix_decision_candidatura ON banco.decision_administrativa(candidatura_id);
CREATE INDEX ix_decision_direccion ON banco.decision_administrativa(solicitud_direccion_id);

CREATE TABLE banco.asignacion_alumno (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidatura_id bigint NOT NULL UNIQUE,
  decision_id bigint NOT NULL UNIQUE REFERENCES banco.decision_administrativa(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  alumno_id bigint NOT NULL REFERENCES banco.alumno(usuario_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  proyecto_id bigint NOT NULL REFERENCES banco.proyecto(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  resultado_decision text GENERATED ALWAYS AS ('aprobada'::text) STORED NOT NULL,
  inicio timestamptz NOT NULL,
  fin timestamptz,
  estado text NOT NULL DEFAULT 'vigente' CHECK (estado IN ('vigente','finalizada','revocada')),
  CONSTRAINT fk_asignacion_alumno_origen FOREIGN KEY (candidatura_id,alumno_id,proyecto_id)
    REFERENCES banco.candidatura(id,alumno_id,proyecto_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_asignacion_alumno_aprobacion FOREIGN KEY (decision_id,candidatura_id,resultado_decision)
    REFERENCES banco.decision_administrativa(id,candidatura_id,resultado) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT ck_asignacion_alumno_fechas CHECK (
    (estado = 'vigente' AND fin IS NULL) OR
    (estado IN ('finalizada','revocada') AND fin IS NOT NULL AND fin > inicio))
);
CREATE UNIQUE INDEX uq_asignacion_alumno_vigente ON banco.asignacion_alumno(alumno_id,proyecto_id) WHERE estado = 'vigente';
CREATE INDEX ix_asignacion_alumno_proyecto ON banco.asignacion_alumno(proyecto_id);
CREATE TABLE banco.asignacion_direccion (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_direccion_id bigint NOT NULL UNIQUE,
  decision_id bigint NOT NULL UNIQUE REFERENCES banco.decision_administrativa(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  profesor_id bigint NOT NULL REFERENCES banco.profesor(usuario_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  proyecto_id bigint NOT NULL REFERENCES banco.proyecto(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  resultado_decision text GENERATED ALWAYS AS ('aprobada'::text) STORED NOT NULL,
  inicio timestamptz NOT NULL,
  fin timestamptz,
  estado text NOT NULL DEFAULT 'vigente' CHECK (estado IN ('vigente','finalizada','revocada')),
  CONSTRAINT fk_asignacion_direccion_origen FOREIGN KEY (solicitud_direccion_id,profesor_id,proyecto_id)
    REFERENCES banco.solicitud_direccion(id,profesor_id,proyecto_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_asignacion_direccion_aprobacion FOREIGN KEY (decision_id,solicitud_direccion_id,resultado_decision)
    REFERENCES banco.decision_administrativa(id,solicitud_direccion_id,resultado) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT ck_asignacion_direccion_fechas CHECK (
    (estado = 'vigente' AND fin IS NULL) OR
    (estado IN ('finalizada','revocada') AND fin IS NOT NULL AND fin > inicio))
);
CREATE UNIQUE INDEX uq_asignacion_direccion_vigente ON banco.asignacion_direccion(profesor_id,proyecto_id) WHERE estado = 'vigente';
CREATE INDEX ix_asignacion_direccion_proyecto ON banco.asignacion_direccion(proyecto_id);
CREATE TABLE banco.acompanamiento (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asignacion_alumno_id bigint NOT NULL REFERENCES banco.asignacion_alumno(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  asignacion_direccion_id bigint NOT NULL REFERENCES banco.asignacion_direccion(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  inicio timestamptz NOT NULL,
  fin timestamptz,
  estado text NOT NULL DEFAULT 'vigente' CHECK (estado IN ('vigente','finalizada','revocada')),
  CONSTRAINT ck_acompanamiento_fechas CHECK (
    (estado = 'vigente' AND fin IS NULL) OR
    (estado IN ('finalizada','revocada') AND fin IS NOT NULL AND fin > inicio))
);
CREATE UNIQUE INDEX uq_acompanamiento_vigente ON banco.acompanamiento(asignacion_alumno_id,asignacion_direccion_id) WHERE estado = 'vigente';
CREATE INDEX ix_acompanamiento_direccion ON banco.acompanamiento(asignacion_direccion_id);

CREATE TABLE banco.evaluacion_candidato (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidatura_id bigint NOT NULL REFERENCES banco.candidatura(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  evaluador_usuario_id bigint NOT NULL REFERENCES banco.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  fecha timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  comentarios text,
  recomendacion text
);
CREATE INDEX ix_evaluacion_candidatura ON banco.evaluacion_candidato(candidatura_id);
CREATE INDEX ix_evaluacion_evaluador ON banco.evaluacion_candidato(evaluador_usuario_id);
CREATE TABLE banco.criterio_evaluacion (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL CHECK (btrim(nombre) <> ''),
  descripcion text,
  escala text,
  ponderacion numeric,
  CONSTRAINT ck_ponderacion_finita CHECK (ponderacion IS NULL OR ponderacion NOT IN ('NaN'::numeric,'Infinity'::numeric,'-Infinity'::numeric))
);
CREATE TABLE banco.detalle_evaluacion (
  evaluacion_id bigint NOT NULL REFERENCES banco.evaluacion_candidato(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  criterio_id bigint NOT NULL REFERENCES banco.criterio_evaluacion(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  puntuacion numeric NOT NULL CHECK (puntuacion NOT IN ('NaN'::numeric,'Infinity'::numeric,'-Infinity'::numeric)),
  comentario text,
  definicion_aplicada jsonb NOT NULL CHECK (jsonb_typeof(definicion_aplicada) = 'object'),
  PRIMARY KEY (evaluacion_id,criterio_id)
);
CREATE INDEX ix_detalle_criterio ON banco.detalle_evaluacion(criterio_id);

CREATE TABLE banco.evento_auditoria (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_usuario_id bigint REFERENCES banco.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  origen text NOT NULL CHECK (origen IN ('usuario','sistema')),
  operacion text NOT NULL CHECK (btrim(operacion) <> ''),
  fecha timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  entidad_afectada text NOT NULL CHECK (btrim(entidad_afectada) <> ''),
  registro_afectado text NOT NULL CHECK (btrim(registro_afectado) <> ''),
  transicion text,
  resultado text NOT NULL CHECK (btrim(resultado) <> ''),
  CONSTRAINT ck_auditoria_actor CHECK (
    (origen = 'usuario' AND actor_usuario_id IS NOT NULL) OR
    (origen = 'sistema' AND actor_usuario_id IS NULL))
);
CREATE INDEX ix_auditoria_actor ON banco.evento_auditoria(actor_usuario_id);
CREATE INDEX ix_auditoria_fecha ON banco.evento_auditoria(fecha);
CREATE TABLE banco.notificacion (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  destinatario_usuario_id bigint NOT NULL REFERENCES banco.usuario(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  evento_id bigint NOT NULL REFERENCES banco.evento_auditoria(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  mensaje text NOT NULL CHECK (btrim(mensaje) <> ''),
  fecha timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_lectura timestamptz,
  CONSTRAINT ck_notificacion_lectura CHECK (fecha_lectura IS NULL OR fecha_lectura >= fecha),
  CONSTRAINT uq_notificacion_evento_destinatario UNIQUE (evento_id,destinatario_usuario_id)
);
CREATE INDEX ix_notificacion_destinatario ON banco.notificacion(destinatario_usuario_id,fecha);

COMMENT ON SCHEMA banco IS 'BD-01 PostgreSQL: integridad estructural. Políticas D-01..D-08/D-10..D-12 y APIs pendientes.';
COMMENT ON COLUMN banco.asignacion_alumno.resultado_decision IS 'Constante generada que exige decisión aprobatoria del mismo objeto mediante FK compuesta.';
COMMENT ON COLUMN banco.asignacion_direccion.resultado_decision IS 'Constante generada que exige decisión aprobatoria del mismo objeto mediante FK compuesta.';
COMMENT ON COLUMN banco.alumno_habilidad.evidencia IS 'Contenido opaco provisional: sin habilitar adjuntos, enlaces públicos ni permisos de D-10/D-11.';
COMMENT ON TABLE banco.notificacion IS 'Estructura persistente; generación, visibilidad y canal condicionados por D-10/D-11. Sin envío externo.';
